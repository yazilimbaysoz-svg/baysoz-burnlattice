from __future__ import annotations

import pytest

from burnlattice.burnrate import generate_rules
from burnlattice.rules import RulesError, find_line, parse_rules, render_rules
from burnlattice.spec import load_contract
from tests.helpers import check, example

_CONTRACT = load_contract(example("checkout-availability.json"))
_EXPECTED = generate_rules(_CONTRACT)


def test_round_trip() -> None:
    text = render_rules(_CONTRACT, _EXPECTED)
    reparsed = parse_rules(text, "generated.yml")
    check(len(reparsed) == len(_EXPECTED), "rule count changed during round trip")
    for before, after in zip(_EXPECTED, reparsed, strict=True):
        check(before.name == after.name, "name changed")
        check(before.expr == after.expr, "expression changed")
        check(before.labels == after.labels, "labels changed")
        check(before.annotations == after.annotations, "annotations changed")
        check(before.for_time == after.for_time, "for duration changed")


def test_generated_yaml_has_provenance() -> None:
    text = render_rules(_CONTRACT, _EXPECTED)
    check("Baysöz Labs <baysozlabs@proton.me>" in text, "attribution missing")
    check(text.startswith("# Generated by burnlattice 1.0.0"), "generator header missing")


def test_find_line() -> None:
    text = render_rules(_CONTRACT, _EXPECTED)
    check(find_line(text, "groups:") == 4, "group header line lookup failed")
    check(parse_rules(text)[0].line > 4, "rule line lookup failed")


@pytest.mark.parametrize(
    "text",
    [
        "groups: [unclosed",
        "rules: []",
        "groups:\n  - name: test\n    rules: not-a-list",
        "groups:\n  - name: test\n    rules:\n      - alert: A\n        expr: up\n        bogus: 1",
        "groups:\n  - name: test\n    rules:\n"
        "      - alert: A\n        record: B\n        expr: up",
        "groups:\n  - name: test\n    rules:\n      - alert: A\n        expr: up\n        for: 5",
    ],
)
def test_malformed_rule_files_are_rejected(text: str) -> None:
    with pytest.raises(RulesError):
        parse_rules(text)


def test_empty_group_is_allowed() -> None:
    check(parse_rules("groups: []\n") == (), "empty rule file should parse")
